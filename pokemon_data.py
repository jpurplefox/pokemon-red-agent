# Status condition bit masks
STATUS_NAMES = {
    0x00: None,         # healthy
    0x04: "PSN",        # poisoned
    0x08: "BRN",        # burned
    0x10: "FRZ",        # frozen
    0x20: "PAR",        # paralyzed
}


def status_text(status_byte):
    """Return human-readable status from the status condition byte."""
    if status_byte == 0:
        return None
    # Sleep: bits 0-2 encode sleep turns remaining (1-7)
    if status_byte & 0x07:
        return "SLP"
    # Other statuses use specific bits
    for mask, name in STATUS_NAMES.items():
        if mask and (status_byte & mask):
            return name
    return None


